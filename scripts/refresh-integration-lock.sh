#!/usr/bin/env bash
# Regenerate requirements-integration.lock: the complete, hash-pinned
# environment for the CI `integration` job (Ubuntu x86_64, Python 3.12).
#
# Inputs:
#   requirements-integration.in  pinned framework versions
#   pyproject.toml               IronMesh's dev + rns extras
#   requirements.lock            versions shared with the unit-test job,
#                                applied as constraints
#
# One exception to the requirements.lock constraints: aiosqlite. crewai
# requires aiosqlite ~=0.21 while the unit lock pins 0.22.x; IronMesh itself
# accepts >=0.19,<1, so the integration environment follows crewai.
#
# The whole graph is resolved in one pass, so it is internally consistent
# (`pip check` clean). Never install the frameworks one at a time on top of
# it. Requires uv (https://docs.astral.sh/uv/).
#
# Usage: bash scripts/refresh-integration-lock.sh   (from the repo root)

set -euo pipefail
cd "$(dirname "$0")/.."

PY_VERSION="3.12"
PLATFORM="x86_64-manylinux_2_28"
EXCLUDED_CONSTRAINTS="aiosqlite"

# The constraints file lives next to requirements.lock (repo-relative) so
# uv's "# via -c ..." annotations name it instead of a machine-specific temp
# path; the annotation is then rewritten to point at requirements.lock.
constraints="requirements.lock.constraints"
out="$(mktemp)"
trap 'rm -f "$constraints" "$out"' EXIT

# Pin lines of requirements.lock (name==version plus any marker), without
# the hash continuations.
grep -E '^[A-Za-z0-9_.-]+==' requirements.lock \
    | sed -e 's/[[:space:]]*\\$//' \
    | grep -v -E "^(${EXCLUDED_CONSTRAINTS})==" > "$constraints"

uv pip compile pyproject.toml requirements-integration.in \
    --extra dev --extra rns \
    --python-version "$PY_VERSION" --python-platform "$PLATFORM" \
    --constraint "$constraints" \
    --generate-hashes --no-header --quiet \
    -o "$out"

{
    cat <<EOF
# Hash-pinned environment for the CI integration job (tests/integration).
#
# GENERATED by scripts/refresh-integration-lock.sh: do not edit by hand.
# Platform: Linux x86_64 (manylinux_2_28), Python ${PY_VERSION} only. This
# is not a universal lock; the integration job runs on ubuntu-latest / 3.12.
#
# Why this exists and how to change the framework versions:
# see requirements-integration.in.
#
# Install (as the integration job does):
#     pip install --require-hashes -r requirements-integration.lock
#     pip install -e . --no-deps
#     pip check
EOF
    sed -e "s|-c ${constraints}|-c requirements.lock|" "$out"
} > requirements-integration.lock

echo "wrote requirements-integration.lock ($(grep -cE '^[A-Za-z0-9_.-]+==' requirements-integration.lock) packages)"
