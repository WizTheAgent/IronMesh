class TestTrustStoreLoad:
    def _agent_key(self, golden_cfg):
        from ironmesh.keys import load_keys
        k = load_keys(str(golden_cfg / "keys.json"), passphrase=PP)
        return k.ed25519_secret[:32]

    def test_pinned_peers_load_and_mac_verifies(self, golden_cfg):
        from ironmesh.trust import TrustStore

        ts = TrustStore(agent_key=self._agent_key(golden_cfg),
                        path=str(golden_cfg / "known_peers.json"))
        # MAC verified against the real 0.9.4.2 envelope -> not latched.
        assert ts._readonly_due_to_mac_failure is False
        peers = ts.list_peers()
        assert len(peers) == len(MANIFEST["peers"])
        for exp in MANIFEST["peers"]:
            assert ts.get_peer(exp["node_id"]) is not None

    def test_wrong_agent_key_latches_readonly_not_wipe(self, golden_cfg):
        """The v0.8.5.6 wipe class: a wrong agent key must fail the MAC, load
        zero peers, and latch read-only — NOT accept a write that flattens the
        on-disk file."""
        from ironmesh.trust import TrustStore

        ts = TrustStore(agent_key=b"\x11" * 32,
                        path=str(golden_cfg / "known_peers.json"))
        assert ts.list_peers() == []
        assert ts._readonly_due_to_mac_failure is True


