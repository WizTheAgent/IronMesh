class TestDbMigrate:
    async def test_reads_real_0942_messages(self, golden_cfg):
        from ironmesh.store import MessageStore

        store = MessageStore(str(golden_cfg / "data.db"), storage_passphrase=PP)
        await store.open()
        try:
            msgs = {m["msg_id"]: m for m in await store.get_messages(limit=100)}
        finally:
            await store.close()

        for exp in MANIFEST["messages"]:
            assert exp["msg_id"] in msgs, f"missing {exp['msg_id']}"
            assert (msgs[exp["msg_id"]]["payload"]
                    == base64.b64decode(exp["payload_b64"]))

    async def test_reads_real_0942_pending_queue(self, golden_cfg):
        from ironmesh.store import MessageStore

        store = MessageStore(str(golden_cfg / "data.db"), storage_passphrase=PP)
        await store.open()
        try:
            pending = await store.get_pending_for_peer(
                MANIFEST["pending"]["peer_node_id"]
            )
        finally:
            await store.close()

        got = {p["msg_id"]: p["payload"] for p in pending}
        for item in MANIFEST["pending"]["items"]:
            assert item["msg_id"] in got, f"missing pending {item['msg_id']}"
            assert got[item["msg_id"]] == base64.b64decode(item["payload_b64"])

    async def test_first_open_upgrades_format_and_introduces_salt(self, golden_cfg):
        from ironmesh.store import STORAGE_FORMAT_AEAD_V2, STORAGE_V2_MAGIC, MessageStore

        db = str(golden_cfg / "data.db")
        store = MessageStore(db, storage_passphrase=PP)
        await store.open()
        await store.close()

        async with aiosqlite.connect(db) as d:
            fmt = await (await d.execute(
                "SELECT value FROM _meta WHERE key = 'storage_format'"
            )).fetchone()
            salt = await (await d.execute(
                "SELECT value FROM _meta WHERE key = 'storage_salt'"
            )).fetchone()
            # every previously-legacy payload is now prefixed
            cur = await d.execute(
                "SELECT payload FROM messages WHERE payload IS NOT NULL"
            )
            rows = await cur.fetchall()

        assert fmt is not None and fmt[0] == STORAGE_FORMAT_AEAD_V2
        assert salt is not None                      # 0.9.4.2 had no salt
        assert all(bytes(p).startswith(STORAGE_V2_MAGIC) for (p,) in rows)

    async def test_reopen_after_migration_round_trips(self, golden_cfg):
        from ironmesh.store import MessageStore

        db = str(golden_cfg / "data.db")
        store1 = MessageStore(db, storage_passphrase=PP)
        await store1.open()
        await store1.close()

        store2 = MessageStore(db, storage_passphrase=PP)
        await store2.open()
        try:
            msgs = {m["msg_id"]: m for m in await store2.get_messages(limit=100)}
        finally:
            await store2.close()
        first = MANIFEST["messages"][0]
        assert msgs[first["msg_id"]]["payload"] == base64.b64decode(first["payload_b64"])

    async def test_wrong_passphrase_does_not_destroy_legacy_rows(self, golden_cfg):
        """A first open under the wrong passphrase must leave the real 0.9.4.2
        payloads byte-untouched (and unstamped), so a later correct open still
        migrates them — the same guarantee test_storage_kdf.py asserts against a
        synthesized DB, here against the real artifact."""
        from ironmesh.store import STORAGE_V2_MAGIC, MessageStore

        db = str(golden_cfg / "data.db")
        wrong = MessageStore(db, storage_passphrase="not-the-passphrase")
        await wrong.open()
        await wrong.close()

        async with aiosqlite.connect(db) as d:
            cur = await d.execute(
                "SELECT payload FROM messages WHERE payload IS NOT NULL"
            )
            rows = await cur.fetchall()
        assert all(not bytes(p).startswith(STORAGE_V2_MAGIC) for (p,) in rows)

        good = MessageStore(db, storage_passphrase=PP)
        await good.open()
        try:
            msgs = {m["msg_id"]: m for m in await good.get_messages(limit=100)}
        finally:
            await good.close()
        first = MANIFEST["messages"][0]
        assert msgs[first["msg_id"]]["payload"] == base64.b64decode(first["payload_b64"])


