class TestIdentityOpen:
    def test_headless_load_with_passphrase(self, golden_cfg):
        from ironmesh.keys import load_keys

        k = load_keys(str(golden_cfg / "keys.json"), passphrase=PP)
        assert (base64.b64encode(k.ed25519_public).decode()
                == MANIFEST["identity"]["ed25519_public_b64"])
        assert k.get_fingerprint() == MANIFEST["identity"]["fingerprint"]
        # 0.9.4.2 wrote the v3 master-seed envelope — the X25519 subkey must
        # come back populated, not fall through to the legacy derivation.
        assert k.get_x25519_public() is not None
        assert k.get_x25519_secret() is not None

    def test_wrong_passphrase_raises(self, golden_cfg):
        from ironmesh.keys import load_keys

        with pytest.raises(Exception):
            load_keys(str(golden_cfg / "keys.json"), passphrase="not-the-pass")

    def test_encrypted_without_passphrase_raises(self, golden_cfg):
        from ironmesh.keys import load_keys

        with pytest.raises(ValueError, match="(?i)encrypted"):
            load_keys(str(golden_cfg / "keys.json"))


