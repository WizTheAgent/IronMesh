class TestFixtureIsGenuinelyLegacy:
    async def test_db_has_no_v2_prefix_and_no_salt(self):
        """The checked-in DB must be pre-v0.9.5 on disk: payloads carry no
        ``IMSTOREv2`` prefix and there is no persisted ``storage_salt``. This
        guards against the fixture being accidentally regenerated by current
        code (which would make every migration assertion below circular)."""
        from ironmesh.store import STORAGE_V2_MAGIC

        async with aiosqlite.connect(str(FIXTURE_DIR / "data.db")) as db:
            cur = await db.execute(
                "SELECT payload FROM messages WHERE payload IS NOT NULL"
            )
            rows = await cur.fetchall()
            assert rows, "fixture DB unexpectedly has no encrypted messages"
            for (payload,) in rows:
                assert not bytes(payload).startswith(STORAGE_V2_MAGIC)
            cur = await db.execute(
                "SELECT value FROM _meta WHERE key = 'storage_salt'"
            )
            assert await cur.fetchone() is None
            cur = await db.execute(
                "SELECT value FROM _meta WHERE key = 'storage_format'"
            )
            assert await cur.fetchone() is None

    def test_manifest_records_real_wheel(self):
        assert "0.9.4.2" in MANIFEST["generated_by"]


