_DOCTOR_CMD = ("import sys; sys.argv = ['ironmesh', 'doctor']; "
               "from ironmesh.cli import main; raise SystemExit(main())")


def _run_doctor(home, extra_env=None, timeout=120):
    """Run doctor in a genuinely headless subprocess (stdin not a tty). The
    timeout IS the regression assertion — the pre-fix code froze forever with
    an existing audit log present."""
    env = {k: v for k, v in os.environ.items()
           if k not in ("IRONMESH_PASSPHRASE", "IRONMESH_KEYS_PASSPHRASE")}
    env["HOME"] = str(home)
    env["USERPROFILE"] = str(home)
    env["PYTHONPATH"] = str(Path(ironmesh.__file__).resolve().parent.parent)
    env["PYTHONUNBUFFERED"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"
    if extra_env:
        env.update(extra_env)
    return subprocess.run(
        [sys.executable, "-c", _DOCTOR_CMD],
        stdin=subprocess.DEVNULL, capture_output=True, encoding="utf-8",
        env=env, timeout=timeout,
    )


class TestDoctorOnReal0942State:
    def test_headless_resolvable_verifies_chain_without_prompt(self, golden_cfg):
        home = golden_cfg.parent
        res = _run_doctor(home, extra_env={"IRONMESH_KEYS_PASSPHRASE": PP})
        combined = res.stdout + res.stderr
        n = MANIFEST["audit_entry_count"]
        assert f"chain verifies clean ({n} entries)" in combined, combined
        assert "Identity key passphrase" not in combined  # never prompted

    def test_headless_unresolvable_errors_not_hangs(self, golden_cfg):
        home = golden_cfg.parent
        res = _run_doctor(home)  # no passphrase available
        combined = res.stdout + res.stderr
        assert res.returncode != 0
        assert "Identity key passphrase" not in combined  # never prompted
