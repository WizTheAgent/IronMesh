"""Existing-state coverage across the 0.9.4.2 -> HEAD version boundary.

Class B root cause (Phase 0 RCA): the autouse ``_isolate_ironmesh_state``
fixture gives every test a pristine EMPTY ``~/.ironmesh``. Nothing exercised a
node with real accumulated state on disk, and two bugs shipped straight through
that hole with a green suite — the TOFU trust-store load and the ``doctor``
headless hang on ``audit.verify_chain``.

These tests point the CURRENT code at a **real** 0.9.4.2 golden fixture
(``tests/fixtures/existing_state/v0_9_4_2/``, written by the actual released
0.9.4.2 wheel — see ``generate_v0942_fixture.py``). That is the non-circular
complement to the two existing suites, which both build their "old" state with
HEAD's own code:

  * ``test_storage_kdf.py`` writes its "legacy" DB with HEAD's
    ``_derive_legacy_storage_key`` — it validates HEAD's *assumption* of the old
    format and would pass even if that assumption were wrong.
  * ``test_doctor_existing_state.py`` builds identity + audit chain with HEAD's
    ``generate_keypair`` / ``AuditLog`` — same circularity.

Here the artifacts were written by 0.9.4.2 itself, so a divergence between what
0.9.4.2 wrote and what HEAD expects is a real, caught failure. Every persisted-
state path Phase 0 flagged as uncovered gets an existing-state variant here,
headless and (where the resolution differs) interactive.
"""

import base64
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import aiosqlite
import pytest

import ironmesh

FIXTURE_DIR = Path(__file__).parent / "fixtures" / "existing_state" / "v0_9_4_2"
MANIFEST = json.loads((FIXTURE_DIR / "manifest.json").read_text())
PP = MANIFEST["passphrase"]

# The golden fixture must be present and genuinely a 0.9.4.2 artifact. If it is
# ever regenerated by newer code this collection guard fails loudly rather than
# silently testing a HEAD-written DB.
pytestmark = pytest.mark.skipif(
    not (FIXTURE_DIR / "data.db").exists(),
    reason="golden 0.9.4.2 fixture missing",
)


@pytest.fixture
def golden_cfg(tmp_path):
    """A writable COPY of the golden 0.9.4.2 ``~/.ironmesh``.

    The checked-in fixture must never be mutated by a migrating open, so each
    test operates on a per-test copy. Returns the ``.ironmesh`` dir.
    """
    cfg = tmp_path / ".ironmesh"
    cfg.mkdir()
    for name in ("keys.json", "known_peers.json", "data.db", "audit.log"):
        shutil.copy(FIXTURE_DIR / name, cfg / name)
    return cfg


def _no_tty(monkeypatch):
    monkeypatch.setattr("ironmesh.cli_output.stdin_is_interactive", lambda: False)


def _clear_pp_env(monkeypatch):
    for var in ("IRONMESH_PASSPHRASE", "IRONMESH_KEYS_PASSPHRASE"):
        monkeypatch.delenv(var, raising=False)


