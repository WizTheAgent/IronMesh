class TestAuditVerify:
    def test_headless_explicit_passphrase(self, golden_cfg, monkeypatch):
        from ironmesh.audit import verify_chain

        _no_tty(monkeypatch)
        ok, entries, first_bad = verify_chain(
            str(golden_cfg / "audit.log"),
            keys_path=str(golden_cfg / "keys.json"),
            keys_passphrase=PP,
        )
        assert ok is True
        assert entries == MANIFEST["audit_entry_count"]
        assert first_bad is None

    def test_headless_env_passphrase(self, golden_cfg, monkeypatch):
        from ironmesh.audit import verify_chain

        _no_tty(monkeypatch)
        monkeypatch.setenv("IRONMESH_KEYS_PASSPHRASE", PP)
        ok, entries, _ = verify_chain(
            str(golden_cfg / "audit.log"),
            keys_path=str(golden_cfg / "keys.json"),
        )
        assert ok is True
        assert entries == MANIFEST["audit_entry_count"]

    def test_headless_no_passphrase_raises_not_hangs(self, golden_cfg, monkeypatch):
        """Doctor-hang regression against a REAL 0.9.4.2 encrypted key file:
        with no passphrase and no TTY, resolution must raise an actionable
        error rather than block on a hidden getpass."""
        import getpass as getpass_mod

        from ironmesh.audit import verify_chain

        _no_tty(monkeypatch)
        _clear_pp_env(monkeypatch)
        monkeypatch.setattr(
            getpass_mod, "getpass",
            lambda prompt="": pytest.fail("getpass called in a headless run"),
        )
        with pytest.raises(ValueError, match="headless"):
            verify_chain(str(golden_cfg / "audit.log"),
                         keys_path=str(golden_cfg / "keys.json"))

    def test_interactive_getpass_resolves(self, golden_cfg, monkeypatch):
        import getpass as getpass_mod

        from ironmesh.audit import verify_chain

        _clear_pp_env(monkeypatch)
        monkeypatch.setattr("ironmesh.cli_output.stdin_is_interactive",
                            lambda: True)
        monkeypatch.setattr(getpass_mod, "getpass", lambda prompt="": PP)
        ok, entries, _ = verify_chain(str(golden_cfg / "audit.log"),
                                      keys_path=str(golden_cfg / "keys.json"))
        assert ok is True
        assert entries == MANIFEST["audit_entry_count"]

    async def test_tampered_entry_is_detected(self, golden_cfg):
        """Flipping a byte in the real 0.9.4.2 chain must be caught by HEAD's
        verifier — proves cross-version verification is genuine, not vacuous."""
        from ironmesh.audit import verify_chain

        log = golden_cfg / "audit.log"
        data = log.read_bytes()
        # Corrupt a byte in the middle of the file (inside an entry, not the
        # trailing newline).
        idx = len(data) // 2
        tampered = bytearray(data)
        tampered[idx] ^= 0x20
        log.write_bytes(bytes(tampered))

        ok, _entries, first_bad = verify_chain(
            str(log), keys_path=str(golden_cfg / "keys.json"),
            keys_passphrase=PP,
        )
        assert ok is False
        assert first_bad is not None


